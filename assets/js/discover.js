/**
 * TyagiHub Ecosystem Platform - JSON Unified Filter & Pagination Engine
 * Handles client-side routing, categories tracking, and dynamic search pagination.
 */

document.addEventListener("DOMContentLoaded", () => {
  const wrapper = document.querySelector("#post-wrapper");
  const searchInput = document.getElementById("discover-search");
  const paginationNav = document.getElementById("pagination-nav");

  if (!wrapper || !searchInput || !paginationNav) return;

  let allPosts = [];
  let filteredPosts = [];
  let currentCategory = "all";
  let searchQuery = "";
  let currentPage = 1;
  const postsPerPage = 6; // Har page par sateek 6 posts dikhengi

  // URL State Parser: Detect Category and Page numbers cleanly from URLs
  function parseCurrentURLState() {
    const path = window.location.pathname.toLowerCase();
    
    // 1. Detect Category Context
    if (path.includes("/cybersecurity/")) currentCategory = "cybersecurity";
    else if (path.includes("/aifuture/")) currentCategory = "aifuture";
    else currentCategory = "all";

    // 2. Detect Page Number Context
    const pageMatch = path.match(/\/page-(\d+)\//) || path.match(/\/page-(\d+)/);
    currentPage = pageMatch ? parseInt(pageMatch[1], 10) : 1;
  }

  // Fetch the centralized JSON map generated by Jekyll
  fetch("/posts.json")
    .then(res => res.json())
    .then(data => {
      allPosts = data;
      parseCurrentURLState();
      executeMasterFilterRouter();
      setupCategoryButtonsActiveState();
    })
    .catch(err => console.error("Error loading posts feed stream:", err));

  // Master Filtering Framework (Category + Real-time Search Matcher)
  function executeMasterFilterRouter() {
    filteredPosts = allPosts.filter(post => {
      // Category Matcher Logic
      const matchesCategory = (currentCategory === "all") || post.categories.includes(currentCategory);
      
      // Search Input Matcher Pool Logic
      const textPool = `${post.title} ${post.description} ${post.categories.join(" ")}`.toLowerCase();
      const matchesSearch = textPool.includes(searchQuery);

      return matchesCategory && matchesSearch;
    });

    // Reset pagination to page 1 if user types into the search pool
    if (searchQuery.length > 0 && currentPage > Math.ceil(filteredPosts.length / postsPerPage)) {
      currentPage = 1;
    }

    renderRequestedViewCards();
    generateDynamicPaginationControls();
  }

  // Render HTML Cards onto the fly DOM Matrix
  function renderRequestedViewCards() {
    wrapper.innerHTML = "";

    if (filteredPosts.length === 0) {
      wrapper.innerHTML = `<p style="text-align:center; padding: 40px 0; color: var(--text-muted); width:100%;">No updates found matching the parameters.</p>`;
      return;
    }

    // Slice calculation for current running page bounds
    const startIndex = (currentPage - 1) * postsPerPage;
    const endIndex = startIndex + postsPerPage;
    const paginatedChunk = filteredPosts.slice(startIndex, endIndex);

    paginatedChunk.forEach(p => {
      const cardHTML = `
        <div class="horizontal-post-card js-post">
          <div class="post-img">
            <span class="post-category">${p.categories[0] ? p.categories[0].toUpperCase() : "TECHNOLOGY"}</span>
            <div class="post-date"><i class="fa-regular fa-calendar"></i> ${p.date}</div>
            <img src="${p.image}" alt="${p.title}" loading="lazy" width="260" height="188">
          </div>
          <div class="post-info">
            <div class="post-top-meta">
              <h2><a href="${p.url}">${p.title}</a></h2>
              <p>${p.description}</p>
            </div>
            <div class="post-footer">
              <button class="native-share-btn" onclick="nativeShare('${p.title.replace(/'/g, "\\'")}', '${p.url}')">
                <i class="fa-solid fa-share-nodes"></i> Share
              </button>
              <a href="${p.url}" class="read-link">Read More →</a>
            </div>
          </div>
        </div>`;
      wrapper.insertAdjacentHTML("beforeend", cardHTML);
    });
  }

  // Recalculate and generate Pagination Links dynamically based on active arrays
  function generateDynamicPaginationControls() {
    paginationNav.innerHTML = "";
    const totalPages = Math.ceil(filteredPosts.length / postsPerPage);

    if (totalPages <= 1) return; // No pagination required if array fits on single page

    const basePath = currentCategory === "all" ? "/discover/" : `/${currentCategory}/`;

    // Arrow Left Button
    if (currentPage > 1) {
      const prevLink = currentPage === 2 ? basePath : `${basePath}page-${currentPage - 1}/`;
      paginationNav.insertAdjacentHTML("beforeend", `<a href="${prevLink}" class="page-btn">←</a>`);
    }

    // Individual Page Nodes
    for (let i = 1; i <= totalPages; i++) {
      const pageLink = i === 1 ? basePath : `${basePath}page-${i}/`;
      if (i === currentPage) {
        paginationNav.insertAdjacentHTML("beforeend", `<span class="page-btn active" style="padding: 8px 14px; background: var(--clr-primary, #f5a623); color: #fff; border-radius: 6px; font-weight: bold;">${i}</span>`);
      } else {
        paginationNav.insertAdjacentHTML("beforeend", `<a href="${pageLink}" class="page-btn" style="padding: 8px 14px; border: 1px solid var(--clr-border); border-radius: 6px;">${i}</a>`);
      }
    }

    // Arrow Right Button
    if (currentPage < totalPages) {
      paginationNav.insertAdjacentHTML("beforeend", `<a href="${basePath}page-${currentPage + 1}/" class="page-btn">→</a>`);
    }
  }

  // Intercept Search inputs dynamically
  searchInput.addEventListener("input", (e) => {
    searchQuery = e.target.value.toLowerCase().trim();
    executeMasterFilterRouter();
  });

  // Global Binding for Interactive Tab Buttons Route Changes
  window.filterCategory = function (category, buttonNode) {
    const targetCat = category.toLowerCase().trim();
    if (targetCat === "all") {
      window.location.href = "/discover/";
    } else {
      window.location.href = `/${targetCat}/`;
    }
  };

  function setupCategoryButtonsActiveState() {
    document.querySelectorAll(".discover-cat-btn").forEach(btn => {
      btn.classList.remove("active");
      // Match raw inner text context to enforce clean active states
      if (btn.outerHTML.toLowerCase().includes(`'${currentCategory}'`)) {
        btn.classList.add("active");
      }
    });
  }
});

// Device Core Native Share Protocols
function nativeShare(title, url) {
  if (navigator.share) {
    navigator.share({ title: title, url: url }).catch(console.error);
  } else {
    navigator.clipboard.writeText(url).then(() => {
      alert("Link copied to clipboard!");
    });
  }
}
